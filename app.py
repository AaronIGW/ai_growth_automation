"""Executive growth marketing and AI client intelligence dashboard."""

import sqlite3
import pandas as pd
import plotly.express as px
import streamlit as st

DB_PATH = "growth_marketing.db"

st.set_page_config(
    page_title="AI Growth & Client Intelligence Engine",
    layout="wide"
)

st.title("B2B Marketing Performance & AI Client Briefings")

@st.cache_data
def load_kpis():
    """Calculates top-line commercial marketing and pipeline metrics."""
    conn = sqlite3.connect(DB_PATH)
    query = """
    SELECT 
        COUNT(fl.lead_id) AS total_leads,
        ROUND(AVG(fl.lead_score), 1) AS avg_score,
        COALESCE(SUM(fb.estimated_mrr_usd), 0) AS total_pipeline_mrr,
        (SELECT SUM(spend_to_date_usd) FROM dim_campaigns) AS total_ad_spend
    FROM fact_leads fl
    LEFT JOIN fact_ai_briefings fb ON fl.lead_id = fb.lead_id;
    """
    df = pd.read_sql_query(query, conn)
    conn.close()
    return df.iloc[0]

@st.cache_data
def load_campaign_performance():
    """Aggregates ad spend and pipeline revenue generation by acquisition channel."""
    conn = sqlite3.connect(DB_PATH)
    query = """
    SELECT 
        dc.channel,
        dc.campaign_name,
        dc.spend_to_date_usd,
        COUNT(fl.lead_id) AS total_leads,
        SUM(CASE WHEN fl.qualification_tier = 'High-Priority' THEN 1 ELSE 0 END) AS high_priority_leads,
        COALESCE(SUM(fb.estimated_mrr_usd), 0) AS generated_pipeline_mrr
    FROM dim_campaigns dc
    LEFT JOIN fact_leads fl ON dc.campaign_id = fl.campaign_id
    LEFT JOIN fact_ai_briefings fb ON fl.lead_id = fb.lead_id
    GROUP BY dc.channel, dc.campaign_name, dc.spend_to_date_usd
    ORDER BY generated_pipeline_mrr DESC;
    """
    df = pd.read_sql_query(query, conn)
    conn.close()
    return df

@st.cache_data
def load_tier_breakdown():
    """Calculates distribution of inbound leads across qualification tiers."""
    conn = sqlite3.connect(DB_PATH)
    query = """
    SELECT 
        qualification_tier,
        COUNT(lead_id) AS lead_count,
        ROUND(AVG(stated_budget_monthly_usd), 2) AS avg_monthly_budget
    FROM fact_leads
    GROUP BY qualification_tier
    ORDER BY lead_count DESC;
    """
    df = pd.read_sql_query(query, conn)
    conn.close()
    return df

def fetch_client_briefing(lead_id):
    """Retrieves detailed AI briefing for a selected prospect."""
    conn = sqlite3.connect(DB_PATH)
    query = """
    SELECT 
        fl.company_name,
        fl.employee_count,
        fl.primary_need,
        fl.urgency_level,
        fl.lead_score,
        fb.recommended_package,
        fb.estimated_mrr_usd,
        fb.executive_summary,
        fb.discovery_call_strategy
    FROM fact_leads fl
    JOIN fact_ai_briefings fb ON fl.lead_id = fb.lead_id
    WHERE fl.lead_id = ?;
    """
    df = pd.read_sql_query(query, conn, params=(lead_id,))
    conn.close()
    return df.iloc[0] if not df.empty else None

# Metric Banner
kpi = load_kpis()
c1, c2, c3, c4 = st.columns(4)
c1.metric("Qualified Inquiries", f"{int(kpi['total_leads']):,}")
c2.metric("Pipeline MRR Value", f"${kpi['total_pipeline_mrr']:,.2f}")
c3.metric("Total Marketing Spend", f"${kpi['total_ad_spend']:,.2f}")
c4.metric("Average Lead Score", f"{kpi['avg_score']} / 100")

st.markdown("---")

tab1, tab2 = st.tabs(["Marketing ROI & Acquisition Analytics", "AI Sales Briefing Dossier"])

with tab1:
    col_a, col_b = st.columns([3, 2])
    campaign_df = load_campaign_performance()
    tier_df = load_tier_breakdown()

    with col_a:
        st.subheader("Pipeline MRR Generated by Campaign Source")
        fig_mrr = px.bar(
            campaign_df,
            x="campaign_name",
            y="generated_pipeline_mrr",
            color="channel",
            labels={"campaign_name": "Campaign", "generated_pipeline_mrr": "Projected Monthly Revenue ($)"},
            text_auto=".2s"
        )
        fig_mrr.update_layout(xaxis_tickangle=-25, height=420)
        st.plotly_chart(fig_mrr, use_container_width=True)

    with col_b:
        st.subheader("Inbound Qualification Tiers")
        fig_tier = px.pie(
            tier_df,
            names="qualification_tier",
            values="lead_count",
            color="qualification_tier",
            color_discrete_map={
                "High-Priority": "#1f77b4",
                "Warm": "#ff7f0e",
                "Cold": "#7f7f7f"
            },
            hole=0.45
        )
        fig_tier.update_layout(height=420)
        st.plotly_chart(fig_tier, use_container_width=True)

with tab2:
    st.subheader("Automated Account Executive Playbooks")
    
    conn = sqlite3.connect(DB_PATH)
    lead_choices = pd.read_sql_query(
        """
        SELECT fl.lead_id, fl.company_name || ' (' || fl.lead_score || ' pts)' AS display_label
        FROM fact_leads fl
        JOIN fact_ai_briefings fb ON fl.lead_id = fb.lead_id
        ORDER BY fl.lead_score DESC;
        """,
        conn
    )
    conn.close()

    selected_label = st.selectbox(
        "Select High-Priority Prospect to Review Briefing:",
        options=lead_choices["display_label"]
    )

    if selected_label:
        selected_lead_id = lead_choices.loc[
            lead_choices["display_label"] == selected_label, "lead_id"
        ].values[0]
        
        detail = fetch_client_briefing(selected_lead_id)
        if detail is not None:
            st.markdown(f"### {detail['company_name']}")
            m1, m2, m3, m4 = st.columns(4)
            m1.markdown(f"**Seat Count:** {detail['employee_count']}")
            m2.markdown(f"**Core Need:** {detail['primary_need']}")
            m3.markdown(f"**Urgency:** {detail['urgency_level']}")
            m4.markdown(f"**Target MRR:** ${detail['estimated_mrr_usd']:,.2f}")

            st.info(f"**Recommended Package:** {detail['recommended_package']}")
            st.markdown("**Executive Opportunity Summary:**")
            st.write(detail["executive_summary"])

            st.markdown("**Account Executive Discovery Strategy:**")
            st.write(detail["discovery_call_strategy"])